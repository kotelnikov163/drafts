# Объявляем функцию-генератор. Ключевое слово yield делает её таковой.
def calc_squares(start, stop):
    # Цикл будет проходить от start (включительно) до stop (не включая).
    for i in range(start, stop):
        # yield приостанавливает функцию и возвращает квадрат текущего числа.
        # При следующем запросе цикл продолжится с этого же места.
        yield i * i

# Создаем объект-генератор. Важно: код внутри функции пока НЕ выполняется.
# Он просто "запоминает" параметры: start=5, stop=10.
generator = calc_squares(5, 10)

# --- Первый перебор ---
# Функция list() заставляет генератор запуститься и выдать все значения.
# Это исчерпывает генератор: он доходит до конца и больше не может выдавать числа.
print(list(generator))
# Вывод: [25, 36, 49, 64, 81] (квадраты чисел 5, 6, 7, 8, 9)

# --- Второй перебор ---
# Мы снова пытаемся перебрать ТОТ ЖЕ САМЫЙ объект-генератор.
# Но он уже пуст, так как был исчерпан в предыдущей строке.
print(list(generator))
# Вывод: [] (пустой список)