# ------------------------------------------------------------
# 10. СВОДНАЯ ТАБЛИЦА
# ------------------------------------------------------------
#              list   tuple   dict   set
# изменяемый    ✅     ❌     ✅     ✅
# упорядочен    ✅     ✅     ✅     ❌
# дубликаты     ✅     ✅   ключи❌  ❌
# индексация    ✅     ✅   по ключу ❌
# хэшируемый    ❌     ✅     ❌     ❌
# поиск         O(n)   O(n)   O(1)   O(1)
#
# Когда использовать:
#   list  — упорядоченная изменяемая коллекция
#   tuple — неизменяемая коллекция, ключ dict, возврат из функции
#   dict  — пары ключ-значение, быстрый поиск O(1)
#   set   — уникальные элементы, проверка in за O(1)