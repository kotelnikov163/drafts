import random  # Подключаем модуль random для генерации случайных чисел

# Создаём список списков: 3 участка, на каждом по 4 грядки.
# Каждое значение — случайное число от 5 до 20 (урожай с одной грядки).
harvest = [[random.randint(5, 20) for _ in range(4)] for _ in range(3)]

# Функция для подсчёта общего урожая со всех участков.
def total_harvest(harvest):
    # sum(plot) — сумма урожая на одном участке,
    # внешний sum(...) складывает результаты по всем участкам.
    return sum(sum(plot) for plot in harvest)

# Функция для подсчёта среднего урожая с каждого участка.
def average_harvest_per_plot(harvest):
    # Для каждого участка считаем сумму и делим на количество грядок.
    # Возвращаем список средних значений — по одному на каждый участок.
    return [sum(plot) / len(plot) for plot in harvest]

# Выводим исходные данные: урожай с каждой грядки на каждом участке
print('Урожай с каждой грядки на каждом участке:', harvest)

# Выводим общий урожай со всех участков (одно число)
print('Общий урожай со всех участков:', total_harvest(harvest))

# Выводим средний урожай по каждому участку (список чисел)
print('Средний урожай с каждого участка:', average_harvest_per_plot(harvest))