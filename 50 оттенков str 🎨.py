s = "  Hello, World!  "

# ------------------------------------------------------------
# 🔍 ПОИСК И ПРОВЕРКА
# ------------------------------------------------------------
"abc".find("b")           # 1        — индекс первого вхождения (-1 если нет)
"abab".rfind("a")         # 2        — индекс последнего вхождения
"abc".index("c")          # 2        — как find, но ValueError если нет
"abab".rindex("a")        # 2        — последнее вхождение, ValueError если нет
"aaa".count("a")          # 3        — количество вхождений
"abc".startswith("ab")    # True     — начинается ли с
"abc".endswith("bc")      # True     — заканчивается ли на
"b" in "abc"              # True     — проверка вхождения

# ------------------------------------------------------------
# 🔤 РЕГИСТР
# ------------------------------------------------------------
"abc".upper()             # 'ABC'          — В ВЕРХНИЙ РЕГИСТР
"ABC".lower()             # 'abc'          — в нижний регистр
"hello world".capitalize()# 'Hello world'  — первая заглавная
"hello world".title()     # 'Hello World'  — Каждое Слово С Заглавной
"AbC".swapcase()          # 'aBc'          — инвертировать регистр
"AbC".casefold()          # 'abc'          — агрессивный lower

# ------------------------------------------------------------
# ✂️ ИЗМЕНЕНИЕ И ОЧИСТКА
# ------------------------------------------------------------
"  hi  ".strip()          # 'hi'      — убрать пробелы с обоих концов
"xxhixx".strip("x")       # 'hi'      — убрать указанные символы
"  hi".lstrip()           # 'hi'      — убрать слева
"hi  ".rstrip()           # 'hi'      — убрать справа
"banana".replace("a","o") # 'bonono'  — заменить подстроку
"a\tb".expandtabs(4)      # 'a   b'   — заменить \t на пробелы

# ------------------------------------------------------------
# 🔗 РАЗДЕЛЕНИЕ И СОЕДИНЕНИЕ
# ------------------------------------------------------------
"a,b,c".split(",")        # ['a','b','c']    — разбить в список
"a,b,c".rsplit(",", 1)    # ['a,b','c']      — разбить справа
"a\nb".splitlines()       # ['a','b']        — разбить по строкам
"-".join(['a','b'])       # 'a-b'            — соединить
"a=b".partition("=")      # ('a','=','b')    — разбить на 3 части
"a=b=c".rpartition("=")   # ('a=b','=','c')  — разбить справа

# ------------------------------------------------------------
# 🎨 ФОРМАТИРОВАНИЕ И ВЫРАВНИВАНИЕ
# ------------------------------------------------------------
"{} {}".format("a","b")   # 'a b'      — форматирование
"{name}".format_map({"name":"Bob"})  # 'Bob'
"hi".center(10, "-")      # '----hi----'  — центрировать
"hi".ljust(5, ".")        # 'hi...'       — выровнять влево
"hi".rjust(5, ".")        # '...hi'       — выровнять вправо
"42".zfill(5)             # '00042'       — заполнить нулями
f"{3.14159:.2f}"          # '3.14'        — f-строки

# ------------------------------------------------------------
# ✅ ПРОВЕРКА ТИПА СИМВОЛОВ
# ------------------------------------------------------------
"abc".isalpha()           # True  — только буквы
"123".isdigit()           # True  — только цифры
"½".isnumeric()           # True  — числовые символы
"123".isdecimal()         # True  — десятичные цифры
"abc123".isalnum()        # True  — буквы и/или цифры
"   ".isspace()           # True  — только пробельные
"ABC".isupper()           # True  — все заглавные
"abc".islower()           # True  — все строчные
"Hello World".istitle()   # True  — Слова С Заглавной
"abc".isidentifier()      # True  — валидный идентификатор
"abc".isprintable()       # True  — все печатаемые
"abc".isascii()           # True  — все ASCII

# ------------------------------------------------------------
# 🔐 КОДИРОВАНИЕ
# ------------------------------------------------------------
"abc".encode("utf-8")     # b'abc'                — строка → байты
b"abc".decode("utf-8")    # 'abc'                 — байты → строка

# ------------------------------------------------------------
# 💡 ПРИМЕРЫ
# ------------------------------------------------------------
"  hello, world  ".strip().split(", ")   # ['hello', 'world']
"{:>10}".format("hi")                    # '        hi'
"Hello123".isalnum()                     # True
"banana".replace("a","o").count("o")     # 3
", ".join(["a","b","c"])                 # 'a, b, c'

# ------------------------------------------------------------
# ⚠️ ВАЖНО ПОМНИТЬ
# ------------------------------------------------------------
# 1. Строки НЕИЗМЕНЯЕМЫ — все методы возвращают НОВУЮ строку.
# 2. split() без аргумента режет по любым пробельным символам.
# 3. strip("abc") убирает ЛЮБЫЕ из символов a/b/c, а не подстроку "abc".