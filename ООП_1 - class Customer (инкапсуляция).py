class Customer:
    def __init__(self, name: str):
        # Сохраняем имя покупателя в публичный атрибут
        self.name = name
        # Приватный атрибут "скидка" со значением по умолчанию 10.
        # Два подчёркивания в начале имени делают атрибут приватным
        # (name mangling: снаружи он будет доступен как _Customer__discount).
        self.__discount = 10

    def set_discount(self, new_value: int):
        # Метод принимает новое значение скидки.
        # Обратите внимание: new_value — это параметр метода,
        # поэтому к нему обращаемся БЕЗ self. (никакого self.new_value).
        if new_value > 80:
            # Если новое значение превышает 80 —
            # принудительно ставим максимально допустимые 80.
            self.__discount = 80
        else:
            # Во всех остальных случаях (в том числе 0 и меньше)
            # сохраняем переданное значение как есть.
            self.__discount = new_value
        # Метод ничего не возвращает (return не нужен).

    def get_price(self, price: int) -> float:
        # price — исходная стоимость товара (аргумент метода).
        # Итоговая цена = цена минус скидка:
        #   price - price * discount / 100
        # что то же самое, что:
        #   price * (100 - discount) / 100
        # Результат округляем до двух знаков после запятой.
        return round(price * (100 - self.__discount) / 100, 2)


# ---------- Проверка работы программы ----------

# Создаём объект покупателя:
customer = Customer('Иван Иванович')

# Исходная цена товара
original_price = 85

# Печатаем цену с исходной скидкой (10%):
# 85 * (100 - 10) / 100 = 76.5
print(
    f'С исходной скидкой Иван Иванович заплатит '
    f'{customer.get_price(original_price)} рублей вместо {original_price}'
)

# Изменим скидку до неприемлемого уровня (90).
# Метод set_discount() должен установить размер скидки равным 80,
# потому что больше 80 ставить нельзя.
customer.set_discount(90)

# Печатаем цену с новой скидкой (80%):
# 85 * (100 - 80) / 100 = 17.0
print(
    f'С новой скидкой Иван Иванович заплатит '
    f'{customer.get_price(original_price)} рублей вместо {original_price}'
)