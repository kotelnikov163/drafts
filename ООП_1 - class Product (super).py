# Базовый (родительский) класс для всех товаров
class Product:
    # Инициализатор родительского класса.
    # Принимает название и количество.
    def __init__(self, name, quantity):
        self.name = name          # сохраняем название в атрибут экземпляра
        self.quantity = quantity  # сохраняем количество в атрибут экземпляра

    # Базовый метод, который возвращает краткую информацию о товаре.
    def get_basic_info(self):
        return f'{self.name} (в наличии: {self.quantity})'

    # Заглушка для полной информации. Дочерние классы будут её переопределять.
    def get_full_info(self):
        pass


# Класс-наследник: Гиря (Kettlebell)
class Kettlebell(Product):
    # Переопределяем инициализатор, так как у гири есть дополнительный параметр — вес.
    def __init__(self, name, quantity, weight):
        # Вызываем инициализатор родителя (Product), чтобы он сохранил name и quantity.
        # super() обращается к родительскому классу, self передавать не нужно.
        super().__init__(name, quantity)
        
        # Сохраняем специфичный для гири атрибут — вес.
        self.weight = weight

    # Переопределяем метод, чтобы он возвращал полную информацию (с весом).
    def get_full_info(self):
        # super().get_basic_info() вызывает метод родителя (возвращает "Название (в наличии: N)").
        # Обрати внимание на круглые скобки () после get_basic_info — мы вызываем метод.
        # Добавляем точку и информацию о весе.
        return f'{super().get_basic_info()}. Вес: {self.weight} кг'


# Класс-наследник: Одежда (Clothing)
class Clothing(Product):
    # Переопределяем инициализатор, добавляя размер (size).
    def __init__(self, name, quantity, size):
        # Снова вызываем родительский инициализатор для name и quantity.
        super().__init__(name, quantity)
        
        # Сохраняем специфичный для одежды атрибут — размер.
        self.size = size

    # Переопределяем метод для вывода полной информации (с размером).
    def get_full_info(self):
        # Формируем строку: базовая информация + точка + размер.
        return f'{super().get_basic_info()}. Размер: {self.size}'


# ===== БЛОК ПРОВЕРКИ (для тестирования) =====

# Создаём экземпляр гири: имя "Гантеля", количество 10, вес 5.
small_kettlebell = Kettlebell('Гантеля', 10, 5)

# Создаём экземпляр футболки: имя "Футболка", количество 5, размер 'L'.
shirt = Clothing('Футболка', 5, 'L')

# Вызываем методы и печатаем результат.
print(small_kettlebell.get_full_info())  # Ожидается: Гантеля (в наличии: 10). Вес: 5 кг
print(shirt.get_full_info())             # Ожидается: Футболка (в наличии: 5). Размер: L